-- =========================================================
-- CrimeWatch - schema database Supabase
-- Jalankan di: Supabase Dashboard -> SQL Editor -> New query -> Run
-- Disusun dari query yang dipakai di server/routes/*.js
-- =========================================================

-- 1. Tabel user (profil aplikasi; login tetap lewat Supabase Auth)
create table if not exists public."user" (
  id            bigint generated by default as identity primary key,
  auth_user_id  uuid unique references auth.users(id) on delete cascade,
  email         text not null unique,
  password      text,                         -- hash bcrypt (diisi saat admin daftarkan manager)
  nama          text not null,
  role          text not null default 'manager' check (role in ('admin', 'manager')),
  status        text not null default 'aktif'   check (status in ('aktif', 'nonaktif')),
  last_login    timestamptz,
  created_at    timestamptz not null default now()
);

-- 2. Detail manager (1-1 dengan user)
create table if not exists public.manager_details (
  id            bigint generated by default as identity primary key,
  user_id       bigint not null unique references public."user"(id) on delete cascade,
  organization  text,
  location_url  text,
  latitude      double precision,
  longitude     double precision,
  created_at    timestamptz not null default now()
);

-- 3. Lokasi heatmap
create table if not exists public.heatmap (
  mapid         bigint generated by default as identity primary key,
  nama_lokasi   text not null,
  latitude      double precision not null check (latitude between -90 and 90),
  longitude     double precision not null check (longitude between -180 and 180),
  gmaps_url     text,
  status        text not null default 'aktif' check (status in ('aktif', 'nonaktif')),
  created_at    timestamptz not null default now()
);

-- 4. Data kriminal per lokasi
--    (on delete restrict: admin.js memang menolak hapus lokasi yang masih punya data kriminal)
create table if not exists public.data_kriminal (
  id               bigint generated by default as identity primary key,
  mapid            bigint not null references public.heatmap(mapid) on delete restrict,
  jenis_kejahatan  text not null,
  waktu            timestamptz not null,
  deskripsi        text default '',
  created_at       timestamptz not null default now()
);

create index if not exists data_kriminal_mapid_idx on public.data_kriminal(mapid);
create index if not exists data_kriminal_waktu_idx on public.data_kriminal(waktu desc);
create index if not exists heatmap_status_idx      on public.heatmap(status);
create index if not exists heatmap_lat_lng_idx     on public.heatmap(latitude, longitude);

-- 5. Row Level Security
--    Semua akses data lewat server Express. Server memakai service_role key
--    (server/db.js) yang otomatis melewati RLS. Dengan RLS aktif tanpa policy,
--    anon key dari browser tidak bisa membaca/menulis tabel secara langsung.
alter table public."user"          enable row level security;
alter table public.manager_details enable row level security;
alter table public.heatmap         enable row level security;
alter table public.data_kriminal   enable row level security;

-- 6. Akun admin pertama
--   a) Supabase Dashboard -> Authentication -> Users -> Add user -> Create new user
--      isi email + password, centang "Auto Confirm User"
--   b) Ganti email & nama di bawah, lalu jalankan query ini:
-- =========================================================
insert into public."user" (auth_user_id, email, nama, role, status)
select id, email, 'Administrator', 'admin', 'aktif'
from auth.users
where email = 'admin@contoh.com';
